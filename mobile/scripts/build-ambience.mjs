#!/usr/bin/env node
/**
 * Scans assets/ambience/bed and assets/ambience/accents and writes
 * src/data/ambienceManifest.ts so the app bundles those sounds.
 *
 *   npm run ambience
 *
 * bed/     → looping background tracks (one is picked per session)
 * rhythm/  → short sounds played on every beat, in time with the rhythm
 * accents/ → short one-shots (breaths, sighs…) played in between
 * cries/   → louder exclamations (voices crying out), only in the voice's pauses
 * Supported: .mp3 .m4a .aac .wav
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = /\.(mp3|m4a|aac|wav)$/i;

export function writeAmbienceManifest() {
  const out = ['// AUTO-GENERATED by scripts/build-ambience.mjs — do not edit by hand.', '', 'export const AMBIENCE: { bed: number[]; rhythm: number[]; accents: number[]; cries: number[] } = {'];
  const counts = {};
  for (const group of ['bed', 'rhythm', 'accents', 'cries']) {
    const dir = path.join(root, 'assets', 'ambience', group);
    const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => EXT.test(f)).sort() : [];
    counts[group] = files.length;
    out.push(`  ${group}: [`);
    for (const f of files) out.push(`    require('../../assets/ambience/${group}/${f}'),`);
    out.push('  ],');
  }
  out.push('};', '');
  fs.writeFileSync(path.join(root, 'src', 'data', 'ambienceManifest.ts'), out.join('\n'));
  return counts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = writeAmbienceManifest();
  console.log(`Ambience manifest updated: ${c.bed} bed, ${c.rhythm} rhythm, ${c.accents} accent, ${c.cries} cry sound(s).`);
}
